def parse(path):
    text = path.read_text()
    match = re.match(r"^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$", text)
    if not match:
        return None
    fields = {}
    for line in match.group(1).splitlines():
        key, sep, value = line.partition(":")
        if sep:
            value = value.strip()
            if len(value) > 1 and value[0] == value[-1] and value[0] in "\"'":
                value = value[1:-1]
            fields[key.strip()] = value
    if not fields.get("title") or not fields.get("date"):
        return None
    raw = fields["date"]
    when = datetime.datetime.fromisoformat(raw.replace("Z", "+00:00"))
    if when.tzinfo is None:
        when = when.replace(tzinfo=datetime.timezone.utc)
    return {"id": path.stem, "title": fields["title"], "when": when, "body": match.group(2).strip()}


def relink(match):
    target = match.group(1)
    if target.startswith("https://docs.shapes.inc"):
        target = target[len("https://docs.shapes.inc"):] or "/"
    elif target.startswith("/"):
        target = APP + target
    return "](" + target + ")"


def to_mdx(body):
    """Keep the words; only make the Markdown safe for MDX and fix link targets."""
    out = []
    for line in body.splitlines():
        if re.match(r"^(import|export)\s", line):
            line = "​" + line
        parts = line.split("`")
        for i in range(0, len(parts), 2):  # outside inline code
            part = parts[i]
            part = part.replace("{", "\\{").replace("}", "\\}").replace("<", "&lt;")
            part = re.sub(r"(?<!\\)\$", r"\\$", part)
            part = re.sub(r"\]\(([^)\s]+)\)", relink, part)
            parts[i] = part
        out.append("`".join(parts))
    return "\n".join(out)


def attr(value):
    return value.replace("&", "&amp;").replace('"', "&quot;")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    source = pathlib.Path(sys.argv[1]) / "content" / "whats-new"
    now = datetime.datetime.now(datetime.timezone.utc)
    releases = [r for r in (parse(p) for p in sorted(source.glob("2*.md"))) if r and r["when"] <= now]
    releases.sort(key=lambda r: r["when"], reverse=True)
    blocks = []
    for r in releases:
        label = f"{r['when'].strftime('%B')} {r['when'].day}, {r['when'].year}"
        guides = GUIDES.get(r["id"], [])
        tail = "\n\nGuides: " + ", ".join(f"[{name}]({href})" for name, href in guides) if guides else ""
        blocks.append(f'<Update label="{attr(label)}">\n\n## {r["title"]}\n\n{to_mdx(r["body"])}{tail}\n\n</Update>')
    page = PAGE.read_text()
    if START not in page or END not in page:
        sys.exit("whats-new.mdx is missing the releases:start / releases:end markers")
    head, rest = page.split(START, 1)
    tail = rest.split(END, 1)[1]
    PAGE.write_text(head + START + "\n\n" + "\n\n".join(blocks) + "\n\n" + END + tail)
    print(f"wrote {len(releases)} releases to {PAGE.name}")


if __name__ == "__main__":
    main()
